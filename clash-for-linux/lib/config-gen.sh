#!/usr/bin/env bash
# ============================================================================
# clash-for-linux — Config generation
# ============================================================================

generate_config() {
  local secret mode
  secret="${1:-$(openssl rand -hex 16 2>/dev/null || echo "clash-$(date +%s)")}"
  mode="${2:-tun}"  # tun | fake-ip | redirect

  mkdir -p "$CONF_DIR" "$RULES_DIR" "$PROVIDERS_DIR"

  case "$mode" in
    fake-ip) gen_fakeip_config "$secret" ;;
    redirect) gen_redirect_config "$secret" ;;
    *) gen_tun_config "$secret" ;;
  esac
}

# --- TUN mode (default, recommended) ---
gen_tun_config() {
