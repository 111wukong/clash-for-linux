# mihomo config — generated by clash-for-linux v2
# Mode: Redirect (iptables-based transparent proxy)
# ============================================================================

mixed-port: 7890
redir-port: 7892
tproxy-port: 7893

external-controller: 0.0.0.0:9090
secret: "${secret}"

allow-lan: true
bind-address: "*"
log-level: info
ipv6: false
mode: rule
unified-delay: true

geodata-mode: true

profile:
  store-selected: true

dns:
  enable: true
  listen: 0.0.0.0:53
  ipv6: false
  default-nameserver:
    - 223.5.5.5
    - 114.114.114.114
  nameserver:
    - https://dns.alidns.com/dns-query
    - https://doh.pub/dns-query
  fallback:
    - https://1.1.1.1/dns-query
    - https://dns.google/dns-query
  fallback-filter:
    geoip: true
    geoip-code: CN

rules:
  - GEOSITE,category-ads-all,REJECT
  - GEOSITE,private,DIRECT
  - GEOSITE,microsoft@cn,DIRECT
  - GEOSITE,apple-cn,DIRECT
  - GEOSITE,google-cn,DIRECT
  - GEOSITE,category-games@cn,DIRECT
  - GEOSITE,cn,DIRECT
  - GEOIP,CN,DIRECT
  - MATCH,Proxy
EOF

  echo "$secret"
}

